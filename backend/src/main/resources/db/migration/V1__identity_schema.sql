CREATE TABLE municipality (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_municipality_name UNIQUE (name)
);

CREATE TABLE team (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipality_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_team_municipality FOREIGN KEY (municipality_id)
        REFERENCES municipality (id) ON DELETE RESTRICT,
    CONSTRAINT uq_team_municipality_name UNIQUE (municipality_id, name),
    CONSTRAINT uq_team_id_municipality UNIQUE (id, municipality_id)
);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipality_id BIGINT NOT NULL,
    team_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    login VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(40) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'INACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_app_user_login UNIQUE (login),
    CONSTRAINT ck_app_user_role CHECK (role IN (
        'MUNICIPAL_ADMINISTRATOR',
        'FIELD_WORKER',
        'FLEET_OPERATOR',
        'FIELD_TECHNICIAN',
        'CLIENT_MANAGER',
        'PLATFORM_ADMIN'
    )),
    CONSTRAINT ck_app_user_status CHECK (status IN ('INACTIVE', 'ACTIVE')),
    CONSTRAINT fk_app_user_municipality FOREIGN KEY (municipality_id)
        REFERENCES municipality (id) ON DELETE RESTRICT,
    CONSTRAINT fk_app_user_team_municipality FOREIGN KEY (team_id, municipality_id)
        REFERENCES team (id, municipality_id) ON DELETE RESTRICT
);

CREATE INDEX ix_app_user_municipality ON app_user (municipality_id);
CREATE INDEX ix_app_user_role ON app_user (role);
CREATE INDEX ix_app_user_status ON app_user (status);
