package pt.ua.MovingTree.services;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.mockito.Mockito.when;
import static pt.ua.MovingTree.support.IdentityTestData.municipality;
import static pt.ua.MovingTree.support.IdentityTestData.team;
import static pt.ua.MovingTree.support.IdentityTestData.user;

import jakarta.persistence.EntityManager;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.transaction.annotation.Transactional;
import pt.ua.MovingTree.dtos.UpdateUserRequest;
import pt.ua.MovingTree.dtos.UserResponse;
import pt.ua.MovingTree.enums.AppUserRole;
import pt.ua.MovingTree.exceptions.UserNotFoundException;
import pt.ua.MovingTree.security.CallerGuard;
import pt.ua.MovingTree.support.PostgresIntegrationTest;

@SpringBootTest
@Transactional
class UserUpdateServiceIT extends PostgresIntegrationTest {
    @Autowired
    private UserUpdateService updateService;
    @Autowired
    private JdbcTemplate jdbc;
    @Autowired
    private EntityManager entityManager;
    @MockitoBean
    private CallerGuard callerGuard;

    //passa, role e team mudam sem recriar o utilizador nem apagar trips e reports anteriores
    @Test
    void updatesRoleAndTeamWithoutTouchingHistory() {
        long municipalityId = municipality(jdbc, "update-history-a");
        long oldTeamId = team(jdbc, municipalityId, "parks-update-history");
        long newTeamId = team(jdbc, municipalityId, "ops-update-history");
        long userId = user(jdbc, municipalityId, oldTeamId, "Ana", "ana.update-history", "FIELD_WORKER", "ACTIVE");
        seedHistory(userId);
        Map<String, Object> before = userRow(userId);
        List<Map<String, Object>> tripsBefore = historyRows("put_trip_history");
        List<Map<String, Object>> reportsBefore = historyRows("put_report_history");

        when(callerGuard.requireMunicipalAdministrator()).thenReturn(municipalityId);
        UserResponse response = updateService.update(userId,
                new UpdateUserRequest(AppUserRole.FIELD_TECHNICIAN, newTeamId));
        entityManager.flush();

        Map<String, Object> after = userRow(userId);
        assertEquals("FIELD_TECHNICIAN", after.get("role"));
        assertEquals(newTeamId, ((Number) after.get("team_id")).longValue());
        assertEquals(before.get("id"), after.get("id"));
        assertEquals(before.get("municipality_id"), after.get("municipality_id"));
        assertEquals(before.get("name"), after.get("name"));
        assertEquals(before.get("username"), after.get("username"));
        assertEquals(before.get("password_hash"), after.get("password_hash"));
        assertEquals(before.get("status"), after.get("status"));
        assertEquals(before.get("created_at"), after.get("created_at"));
        assertEquals(AppUserRole.FIELD_TECHNICIAN, response.role());
        assertEquals(newTeamId, response.teamId());
        assertEquals(tripsBefore, historyRows("put_trip_history"));
        assertEquals(reportsBefore, historyRows("put_report_history"));
    }

    //falha, utilizador de outro município retorna 404 e permanece intacto
    @Test
    void foreignUserIsNotFoundAndUntouched() {
        long municipalityA = municipality(jdbc, "update-foreign-a");
        long municipalityB = municipality(jdbc, "update-foreign-b");
        long teamA = team(jdbc, municipalityA, "parks-update-foreign-a");
        long teamB = team(jdbc, municipalityB, "parks-update-foreign-b");
        long foreignUserId = user(jdbc, municipalityB, teamB, "Daniel", "daniel.update-foreign", "FIELD_WORKER", "ACTIVE");
        Map<String, Object> before = userRow(foreignUserId);

        when(callerGuard.requireMunicipalAdministrator()).thenReturn(municipalityA);
        UserNotFoundException exception = assertThrows(UserNotFoundException.class,
                () -> updateService.update(foreignUserId, new UpdateUserRequest(AppUserRole.FLEET_OPERATOR, teamA)));

        assertEquals("User not found", exception.getMessage());
        assertEquals(before, userRow(foreignUserId));
    }

    private void seedHistory(long userId) {
        jdbc.execute("drop table if exists put_trip_history");
        jdbc.execute("""
                create temp table put_trip_history (
                    id bigint generated by default as identity primary key,
                    user_id bigint not null,
                    label varchar(255) not null
                ) on commit drop
                """);
        jdbc.execute("drop table if exists put_report_history");
        jdbc.execute("""
                create temp table put_report_history (
                    id bigint generated by default as identity primary key,
                    user_id bigint not null,
                    label varchar(255) not null
                ) on commit drop
                """);
        jdbc.update("insert into put_trip_history (user_id, label) values (?, ?)", userId, "past-trip");
        jdbc.update("insert into put_report_history (user_id, label) values (?, ?)", userId, "past-report");
    }

    private List<Map<String, Object>> historyRows(String table) {
        return jdbc.queryForList("select id, user_id, label from " + table + " order by id");
    }

    private Map<String, Object> userRow(long userId) {
        return jdbc.queryForMap("""
                select id, municipality_id, team_id, name, username, password_hash, role, status, created_at
                from app_user where id = ?
                """, userId);
    }
}
