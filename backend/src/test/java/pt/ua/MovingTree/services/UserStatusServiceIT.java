package pt.ua.MovingTree.services;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.mockito.Mockito.when;
import static pt.ua.MovingTree.support.IdentityTestData.municipality;
import static pt.ua.MovingTree.support.IdentityTestData.team;
import static pt.ua.MovingTree.support.IdentityTestData.user;

import jakarta.persistence.EntityManager;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.transaction.annotation.Transactional;
import pt.ua.MovingTree.dtos.UpdateUserStatusRequest;
import pt.ua.MovingTree.dtos.UserResponse;
import pt.ua.MovingTree.enums.AppUserRole;
import pt.ua.MovingTree.enums.AppUserStatus;
import pt.ua.MovingTree.exceptions.InvalidCredentialsException;
import pt.ua.MovingTree.security.CallerGuard;
import pt.ua.MovingTree.support.PostgresIntegrationTest;

@SpringBootTest
@Transactional
class UserStatusServiceIT extends PostgresIntegrationTest {
    @Autowired
    private UserStatusService statusService;
    @Autowired
    private UserSignInService signInService;
    @Autowired
    private JdbcTemplate jdbc;
    @Autowired
    private PasswordEncoder passwordEncoder;
    @Autowired
    private EntityManager entityManager;
    @MockitoBean
    private CallerGuard callerGuard;

    //passa, ativação permite sign-in, desativação volta a recusar e trips antigas continuam consultáveis
    @Test
    void activationControlsSignInAndKeepsTripHistory() {
        long municipalityId = municipality(jdbc, "status-integration-a");
        long teamId = team(jdbc, municipalityId, "parks-status-integration");
        long userId = user(jdbc, municipalityId, teamId, "Ana", "ana.status-it", "FIELD_WORKER", "INACTIVE");
        jdbc.update("update app_user set password_hash = ? where id = ?",
                passwordEncoder.encode("password123"), userId);
        seedTrip(userId);

        when(callerGuard.requireMunicipalAdministrator()).thenReturn(municipalityId);
        InvalidCredentialsException inactive = assertThrows(InvalidCredentialsException.class,
                () -> signInService.signIn("ana.status-it", "password123"));
        assertEquals("Invalid credentials", inactive.getMessage());

        UserResponse activated = statusService.changeStatus(userId,
                new UpdateUserStatusRequest(AppUserStatus.ACTIVE));
        entityManager.flush();
        assertEquals(AppUserStatus.ACTIVE, activated.status());
        assertEquals("ACTIVE", jdbc.queryForObject(
                "select status from app_user where id = ?", String.class, userId));
        UserResponse signedIn = signInService.signIn("ana.status-it", "password123");
        assertEquals(userId, signedIn.id());
        assertEquals(AppUserRole.FIELD_WORKER, signedIn.role());
        assertEquals(municipalityId, signedIn.municipalityId());

        statusService.changeStatus(userId, new UpdateUserStatusRequest(AppUserStatus.INACTIVE));
        entityManager.flush();
        assertEquals("INACTIVE", jdbc.queryForObject(
                "select status from app_user where id = ?", String.class, userId));
        InvalidCredentialsException deactivated = assertThrows(InvalidCredentialsException.class,
                () -> signInService.signIn("ana.status-it", "password123"));
        assertEquals("Invalid credentials", deactivated.getMessage());

        List<Map<String, Object>> trips = jdbc.queryForList(
                "select id, user_id, label from status_trip_history order by id");
        assertEquals(1, trips.size());
        assertEquals(userId, ((Number) trips.get(0).get("user_id")).longValue());
        assertEquals("past-trip", trips.get(0).get("label"));
    }

    private void seedTrip(long userId) {
        jdbc.execute("drop table if exists status_trip_history");
        jdbc.execute("""
                create temp table status_trip_history (
                    id bigint generated by default as identity primary key,
                    user_id bigint not null,
                    label varchar(255) not null
                ) on commit drop
                """);
        jdbc.update("insert into status_trip_history (user_id, label) values (?, ?)", userId, "past-trip");
    }
}
